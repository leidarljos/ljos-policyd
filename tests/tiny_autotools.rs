//! A generated Autoconf 2.71 / Automake 1.16 / Libtool tree, judged as
//! `sh ./configure` and as `./configure`. The verdict is the one the
//! check prints. `conftest_ipa8_conftest.oo` stays in the script.

fn check(argv: &[&str]) -> (String, Option<i32>) {
    let dir =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/tiny-autotools");
    let out = std::process::Command::new(env!("CARGO_BIN_EXE_ljos-policyd"))
        .args(argv)
        .current_dir(&dir)
        .env("PHRONESIS_STATE_DIR", dir.join("state"))
        .env_remove("PHRONESIS_WORKSPACE")
        .env_remove("PHRONESIS_JANET_PACK")
        .env_remove("PHRONESIS_PREFIX")
        .env_remove("PHRONESIS_PACK_ROOT")
        .env_remove("CDPATH")
        .output()
        .expect("spawn check");
    (
        String::from_utf8_lossy(&out.stdout).trim().to_string(),
        out.status.code(),
    )
}

#[test]
fn a_generated_configure_is_denied_where_the_tree_is() {
    let dir =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/tiny-autotools");
    let text = std::fs::read_to_string(dir.join("configure")).unwrap();
    let head: Vec<_> = text.lines().take(3).collect();
    assert_eq!(head[0], "#! /bin/sh");
    assert!(head[1].starts_with("# Guess values"));
    assert!(head[2].contains("Generated by GNU Autoconf 2.71"));
    assert!(text.contains("conftest_ipa8_conftest.oo"));
    for argv in [
        ["check", "--", "sh", "./configure"].as_slice(),
        ["check", "--", "./configure"].as_slice(),
    ] {
        let (verdict, code) = check(argv);
        assert_eq!(verdict, "deny\trm-rf-outside-tmp", "{argv:?}");
        assert_eq!(code, Some(2), "{argv:?}");
    }
}
